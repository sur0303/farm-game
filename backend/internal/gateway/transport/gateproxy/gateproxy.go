// Package gateproxy implements the narrow GateStream transport bridge used
// in-process by farm-gate. It deliberately knows nothing about farm
// sessions, owners, or commands: those remain owned by farm-gate.
package gateproxy

import (
	"context"
	"errors"
	"fmt"
	"io"
	"log"
	"strconv"
	"sync"
	"sync/atomic"
	"time"

	"git.internal.example.invalid/mfcn/gateproxy/go-client/pkg/proto/proxypb"
)

var (
	ErrStreamClosed        = errors.New("gateproxy transport: stream closed")
	ErrFrameTooLarge       = errors.New("gateproxy transport: frame exceeds configured limit")
	ErrDownlinkUnavailable = errors.New("gateproxy transport: downlink unavailable")
)

// GateClient is the transport-neutral farm-gate boundary. The production
// implementation is local to farm-gate; tests can use an in-memory client
// without TCONND or a running gateway.
type GateClient interface {
	HandleFrame(context.Context, string, uint64, []byte) ([]byte, error)
	PollDownlink(context.Context, string, uint64) ([]byte, bool, error)
	Disconnect(context.Context, string, uint64) error
}

type preAuthGateClient interface {
	BeginPreAuth(connectionID string, generation uint64, clientIP string) error
	AdmitPreAuth(connectionID string, generation uint64, frameBytes int) error
	IsAuthenticated(connectionID string, generation uint64) bool
	TimeoutPreAuth(connectionID string, generation uint64) bool
	PreAuthMaxFrameBytes() int64
}

// GateStream is the small part of proxypb's generated bidirectional stream
// used by the transport. Keeping this interface local makes the stream boundary
// independently testable and avoids leaking gRPC details into farm-gate.
type GateStream interface {
	Send(*proxypb.GateMsg) error
	Recv() (*proxypb.GateMsg, error)
	Context() context.Context
	CloseSend() error
}

type Config struct {
	MaxFrameBytes        int
	CallTimeout          time.Duration
	HelloTimeout         time.Duration
	DownlinkPollInterval time.Duration
	HeartbeatInterval    time.Duration
	HeartbeatTimeout     time.Duration
	Logger               *log.Logger
}

func (c Config) withDefaults() Config {
	if c.MaxFrameBytes <= 0 {
		c.MaxFrameBytes = 1 << 20
	}
	if c.CallTimeout <= 0 {
		c.CallTimeout = 5 * time.Second
	}
	if c.HelloTimeout <= 0 {
		c.HelloTimeout = 10 * time.Second
	}
	if c.DownlinkPollInterval <= 0 {
		c.DownlinkPollInterval = 50 * time.Millisecond
	}
	if c.HeartbeatInterval <= 0 {
		c.HeartbeatInterval = time.Second
	}
	if c.HeartbeatTimeout <= 0 {
		c.HeartbeatTimeout = 5 * time.Second
	}
	if c.Logger == nil {
		c.Logger = log.Default()
	}
	return c
}

// Transport consumes one gateproxy stream. One transport instance owns one
// GateStream; reconnecting to gateproxy is intentionally handled by the
// process entry point so a broken stream cannot retain stale generations.
type Transport struct {
	client GateClient
	cfg    Config

	sendMu         sync.Mutex // proxypb ClientStream.Send is not safe concurrently.
	mu             sync.Mutex
	states         map[string]*connectionState
	nextGeneration map[string]uint64
	nextConnID     atomic.Int32 // GameSvr-assigned TCONND connection id allocator.
	lastHeartbeat  atomic.Int64
}

type connectionState struct {
	key        string
	head       *proxypb.TconndHead
	generation uint64

	ioMu      sync.Mutex // preserves response/downlink order for this generation.
	stop      chan struct{}
	helloDone chan struct{}
	pollOnce  sync.Once
	closeOnce sync.Once
	helloOnce sync.Once
}

func New(client GateClient, cfg Config) *Transport {
	cfg = cfg.withDefaults()
	return &Transport{client: client, cfg: cfg, states: make(map[string]*connectionState), nextGeneration: make(map[string]uint64)}
}

// Run handles a GateStream until it closes, the context is cancelled, or a
// fatal protocol/transport error occurs. Heartbeats are generated by the
// transport because gateproxy expects its connector peer to keep the stream
// alive; heartbeat T8 semantics remain a deployment probe concern.
func (a *Transport) Run(stream GateStream) error {
	if stream == nil || a.client == nil {
		return errors.New("gateproxy transport: stream and gate client are required")
	}
	ctx, cancel := context.WithCancel(stream.Context())
	defer cancel()
	a.lastHeartbeat.Store(time.Now().UnixMilli())
	recvCh := make(chan *proxypb.GateMsg)
	recvErr := make(chan error, 1)
	go func() {
		for {
			msg, err := stream.Recv()
			if err != nil {
				select {
				case recvErr <- err:
				case <-ctx.Done():
				}
				return
			}
			select {
			case recvCh <- msg:
			case <-ctx.Done():
				return
			}
		}
	}()
	heartbeatErr := make(chan error, 1)
	go func() { heartbeatErr <- a.heartbeatLoop(ctx, stream) }()
	for {
		select {
		case <-ctx.Done():
			a.closeAll(context.Background())
			return ctx.Err()
		case err := <-recvErr:
			a.closeAll(context.Background())
			if errors.Is(err, io.EOF) || errors.Is(ctx.Err(), context.Canceled) {
				return ErrStreamClosed
			}
			return fmt.Errorf("gateproxy transport: gate stream recv: %w", err)
		case err := <-heartbeatErr:
			a.closeAll(context.Background())
			if errors.Is(err, context.Canceled) {
				return ErrStreamClosed
			}
			return err
		case msg := <-recvCh:
			if msg == nil {
				continue
			}
			if hb := msg.GetHeartbeatMsg(); hb != nil {
				a.lastHeartbeat.Store(time.Now().UnixMilli())
				continue
			}
			if tm := msg.GetTconndMsg(); tm != nil {
				if err := a.handle(ctx, stream, tm); err != nil {
					a.closeAll(context.Background())
					return err
				}
				continue
			}
			if batch := msg.GetBatchTconndMsg(); batch != nil {
				for _, tm := range batch.GetMsgs() {
					if err := a.handle(ctx, stream, tm); err != nil {
						a.closeAll(context.Background())
						return err
					}
				}
			}
		}
	}
}

func (a *Transport) heartbeatLoop(ctx context.Context, stream GateStream) error {
	ticker := time.NewTicker(a.cfg.HeartbeatInterval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-ticker.C:
			now := time.Now()
			last := time.UnixMilli(a.lastHeartbeat.Load())
			if now.Sub(last) > a.cfg.HeartbeatTimeout {
				return fmt.Errorf("gateproxy transport: gateproxy heartbeat timeout (%s)", now.Sub(last))
			}
			if err := a.send(stream, &proxypb.GateMsg{Msg: &proxypb.GateMsg_HeartbeatMsg{HeartbeatMsg: &proxypb.HeartbeatMsg{TimeMs: now.UnixMilli()}}}); err != nil {
				return fmt.Errorf("gateproxy transport: send heartbeat: %w", err)
			}
		}
	}
}

func (a *Transport) handle(ctx context.Context, stream GateStream, msg *proxypb.TconndMsg) error {
	if msg == nil || msg.GetHead() == nil {
		return errors.New("gateproxy transport: message head is required")
	}
	key := connectionKey(msg.GetHead())
	switch {
	case msg.GetStartMsg() != nil:
		return a.start(stream, key, msg.GetHead(), msg.GetStartMsg())
	case msg.GetInprocMsg() != nil:
		return a.inproc(ctx, stream, key, msg.GetHead(), msg.GetInprocMsg().GetBody())
	case msg.GetStopMsg() != nil:
		return a.stop(ctx, key, msg.GetHead())
	default:
		return errors.New("gateproxy transport: unknown TCONND message kind")
	}
}

func (a *Transport) start(stream GateStream, key string, head *proxypb.TconndHead, startMsg *proxypb.TconndStartMsg) error {
	// TCONND sends START with a sentinel Id (e.g. -1); the GameSvr must reply
	// with its own assigned Id. TCONND then tags every later INPROC/STOP with
	// that assigned Id, while ConnIdx stays stable for the whole connection.
	// The reply head therefore carries {Id: assigned, ConnIdx: echoed, Extend: 0},
	// matching UC gatesvr. Without this, TCONND never emits the "pass" notify and
	// closes the client with "wait start/relay pkg from svr timeout".
	assignedID := a.nextConnID.Add(1)
	a.cfg.Logger.Printf("[T1] START  key=%s recv_id=%d conn_idx=%d -> assigned_id=%d", key, head.GetId(), head.GetConnIdx(), assignedID)
	a.mu.Lock()
	old := a.states[key]
	generation := a.nextGeneration[key] + 1
	a.nextGeneration[key] = generation
	// Persist the server-assigned head so downlink frames use the same Id.
	replyHead := &proxypb.TconndHead{Id: assignedID, ConnIdx: head.GetConnIdx(), Extend: 0}
	state := newConnectionState(key, replyHead, generation)
	a.states[key] = state
	a.mu.Unlock()
	if old != nil {
		old.close()
		callCtx, cancel := context.WithTimeout(context.Background(), a.cfg.CallTimeout)
		_ = a.client.Disconnect(callCtx, old.key, old.generation)
		cancel()
	}

	// START is a transport admission handshake. Application authentication is
	// still ClientHello, but the connection begins consuming PRE_AUTH resources
	// here, using the source IP supplied by TCONND.
	if lifecycle, ok := a.client.(preAuthGateClient); ok {
		if err := lifecycle.BeginPreAuth(state.key, state.generation, startMsg.GetIp()); err != nil {
			if sendErr := a.sendStartAck(stream, replyHead); sendErr != nil {
				return sendErr
			}
			a.cfg.Logger.Printf("[T1] PRE_AUTH rejected key=%s: %v", key, err)
			return a.rejectConnection(stream, state)
		}
	}
	if err := a.sendStartAck(stream, replyHead); err != nil {
		return err
	}
	if lifecycle, ok := a.client.(preAuthGateClient); ok {
		go a.watchClientHello(stream, state, lifecycle)
	}
	return nil
}

func (a *Transport) sendStartAck(stream GateStream, replyHead *proxypb.TconndHead) error {
	return a.send(stream, &proxypb.GateMsg{Msg: &proxypb.GateMsg_TconndMsg{TconndMsg: &proxypb.TconndMsg{
		Head: cloneHead(replyHead), Msg: &proxypb.TconndMsg_StartMsg{StartMsg: &proxypb.TconndStartMsg{}},
	}}})
}

func (a *Transport) inproc(ctx context.Context, stream GateStream, key string, head *proxypb.TconndHead, body []byte) error {
	a.cfg.Logger.Printf("[T2] INPROC key=%s len=%d", key, len(body))
	if len(body) == 0 {
		return errors.New("gateproxy transport: empty INPROC body")
	}
	if len(body) > a.cfg.MaxFrameBytes {
		return fmt.Errorf("%w: %d > %d", ErrFrameTooLarge, len(body), a.cfg.MaxFrameBytes)
	}
	state := a.state(key)
	if state == nil {
		// An INPROC without START is isolated to that TCONND connection; a
		// malformed peer must not tear down the multiplexed GateStream.
		return a.sendStop(stream, cloneHead(head))
	}
	state.ioMu.Lock()
	defer state.ioMu.Unlock()
	if lifecycle, ok := a.client.(preAuthGateClient); ok && !lifecycle.IsAuthenticated(state.key, state.generation) {
		if limit := lifecycle.PreAuthMaxFrameBytes(); limit > 0 && int64(len(body)) > limit {
			a.cfg.Logger.Printf("[T2] PRE_AUTH frame too large key=%s len=%d limit=%d", key, len(body), limit)
			return a.rejectConnection(stream, state)
		}
		if err := lifecycle.AdmitPreAuth(state.key, state.generation, len(body)); err != nil {
			a.cfg.Logger.Printf("[T2] PRE_AUTH admission rejected key=%s: %v", key, err)
			return a.rejectConnection(stream, state)
		}
	}
	callCtx, cancel := context.WithTimeout(ctx, a.cfg.CallTimeout)
	response, err := a.client.HandleFrame(callCtx, state.key, state.generation, append([]byte(nil), body...))
	cancel()
	if err != nil {
		// GateStream multiplexes many client connections. A bad ClientHello or
		// one backend failure therefore closes only this connection.
		a.cfg.Logger.Printf("gateproxy frame for %s failed: %v", state.key, err)
		return a.rejectConnection(stream, state)
	}
	if lifecycle, ok := a.client.(preAuthGateClient); ok && lifecycle.IsAuthenticated(state.key, state.generation) {
		state.completeHello()
	}
	if len(response) > a.cfg.MaxFrameBytes {
		return fmt.Errorf("%w: gateway response %d > %d", ErrFrameTooLarge, len(response), a.cfg.MaxFrameBytes)
	}
	if len(response) > 0 {
		if err := a.send(stream, &proxypb.GateMsg{Msg: &proxypb.GateMsg_TconndMsg{TconndMsg: &proxypb.TconndMsg{
			Head: cloneHead(head), Msg: &proxypb.TconndMsg_InprocMsg{InprocMsg: &proxypb.TconndInprocMsg{Body: response, NoEnc: true}},
		}}}); err != nil {
			return err
		}
	}
	a.ensureDownlinkPoller(ctx, stream, state)
	return nil
}

func (a *Transport) stop(ctx context.Context, key string, head *proxypb.TconndHead) error {
	a.cfg.Logger.Printf("[T3] STOP  key=%s", key)
	a.mu.Lock()
	state := a.states[key]
	if state != nil {
		delete(a.states, key)
	}
	a.mu.Unlock()
	if state != nil {
		state.close()
		callCtx, cancel := context.WithTimeout(ctx, a.cfg.CallTimeout)
		err := a.client.Disconnect(callCtx, state.key, state.generation)
		cancel()
		return err
	}
	return nil
}

func (a *Transport) state(key string) *connectionState {
	a.mu.Lock()
	defer a.mu.Unlock()
	return a.states[key]
}

func (a *Transport) ensureDownlinkPoller(ctx context.Context, stream GateStream, state *connectionState) {
	state.pollOnce.Do(func() {
		go func() {
			ticker := time.NewTicker(a.cfg.DownlinkPollInterval)
			defer ticker.Stop()
			for {
				select {
				case <-ctx.Done():
					return
				case <-state.stop:
					return
				case <-ticker.C:
				}
				state.ioMu.Lock()
				pollCtx, cancel := context.WithTimeout(ctx, a.cfg.CallTimeout)
				body, ok, err := a.client.PollDownlink(pollCtx, state.key, state.generation)
				cancel()
				if err != nil {
					state.ioMu.Unlock()
					if !errors.Is(err, ErrDownlinkUnavailable) {
						a.cfg.Logger.Printf("downlink poll for %s failed: %v", state.key, err)
					}
					continue
				}
				if ok && len(body) > 0 && len(body) <= a.cfg.MaxFrameBytes {
					if err := a.send(stream, &proxypb.GateMsg{Msg: &proxypb.GateMsg_TconndMsg{TconndMsg: &proxypb.TconndMsg{
						Head: cloneHead(state.head), Msg: &proxypb.TconndMsg_InprocMsg{InprocMsg: &proxypb.TconndInprocMsg{Body: append([]byte(nil), body...), NoEnc: true}},
					}}}); err != nil {
						state.ioMu.Unlock()
						return
					}
				}
				state.ioMu.Unlock()
			}
		}()
	})
}

func (a *Transport) send(stream GateStream, msg *proxypb.GateMsg) error {
	a.sendMu.Lock()
	defer a.sendMu.Unlock()
	return stream.Send(msg)
}

func (a *Transport) sendStop(stream GateStream, head *proxypb.TconndHead) error {
	return a.send(stream, &proxypb.GateMsg{Msg: &proxypb.GateMsg_TconndMsg{TconndMsg: &proxypb.TconndMsg{
		Head: cloneHead(head), Msg: &proxypb.TconndMsg_StopMsg{StopMsg: &proxypb.TconndStopMsg{}},
	}}})
}

// rejectConnection removes exactly one generation and asks TCONND to close
// it. Callers hold state.ioMu, except START rejection where no frame can race.
func (a *Transport) rejectConnection(stream GateStream, state *connectionState) error {
	a.mu.Lock()
	current := a.states[state.key]
	if current == state {
		delete(a.states, state.key)
	}
	a.mu.Unlock()
	if current != state {
		return nil
	}
	state.close()
	callCtx, cancel := context.WithTimeout(context.Background(), a.cfg.CallTimeout)
	_ = a.client.Disconnect(callCtx, state.key, state.generation)
	cancel()
	return a.sendStop(stream, state.head)
}

func (a *Transport) watchClientHello(stream GateStream, state *connectionState, lifecycle preAuthGateClient) {
	timer := time.NewTimer(a.cfg.HelloTimeout)
	defer timer.Stop()
	select {
	case <-state.helloDone:
		return
	case <-state.stop:
		return
	case <-timer.C:
	}
	state.ioMu.Lock()
	defer state.ioMu.Unlock()
	if lifecycle.IsAuthenticated(state.key, state.generation) {
		state.completeHello()
		return
	}
	if !lifecycle.TimeoutPreAuth(state.key, state.generation) {
		return
	}
	a.cfg.Logger.Printf("[T1] ClientHello timeout key=%s generation=%d", state.key, state.generation)
	if err := a.rejectConnection(stream, state); err != nil {
		a.cfg.Logger.Printf("gateproxy timeout STOP for %s failed: %v", state.key, err)
	}
}

func (a *Transport) closeAll(ctx context.Context) {
	a.mu.Lock()
	states := make([]*connectionState, 0, len(a.states))
	for key, state := range a.states {
		delete(a.states, key)
		states = append(states, state)
	}
	a.mu.Unlock()
	for _, state := range states {
		state.close()
		callCtx, cancel := context.WithTimeout(ctx, a.cfg.CallTimeout)
		_ = a.client.Disconnect(callCtx, state.key, state.generation)
		cancel()
	}
}

func newConnectionState(key string, head *proxypb.TconndHead, generation uint64) *connectionState {
	return &connectionState{
		key: key, head: head, generation: generation,
		stop: make(chan struct{}), helloDone: make(chan struct{}),
	}
}

func (s *connectionState) completeHello() {
	s.helloOnce.Do(func() { close(s.helloDone) })
}

func (s *connectionState) close() {
	s.closeOnce.Do(func() { close(s.stop) })
	s.completeHello()
}

// connectionKey identifies a TCONND connection by ConnIdx only. ConnIdx is the
// one field stable across START/INPROC/STOP; Id starts as a TCONND sentinel and
// then becomes the GameSvr-assigned value, and Extend is not connection-stable,
// so neither may participate in the key (otherwise START and later frames would
// map to different states). Mirrors UC gatesvr's GetSessionByConnIdx.
func connectionKey(head *proxypb.TconndHead) string {
	if head == nil {
		return ""
	}
	return "tconnd:" + strconv.FormatInt(int64(head.ConnIdx), 10)
}

func cloneHead(head *proxypb.TconndHead) *proxypb.TconndHead {
	if head == nil {
		return nil
	}
	return &proxypb.TconndHead{Id: head.Id, ConnIdx: head.ConnIdx, Extend: head.Extend}
}
